#include "libft.h"

int	ft_atoi(const char *s)
{
	int	sign;
	int	result;

	while (*s == ' ' || (*s >= '\t' && *s <= '\r'))
		s++;
	sign = 1;
	if (*s == '-' || *s == '+')
	{
		if (*s == '-')
			sign = -1;
		s++;
	}
	result = 0;
	while (*s >= '0' && *s <= '9')
	{
		result = result * 10 - (*s - '0');
		s++;
	}
	if (sign == -1)
		return (result);
	return (-result);
}
